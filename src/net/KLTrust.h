#import <Foundation/Foundation.h>
#import <Security/Security.h>

/**
 * Проверка цепочки сертификатов — одна на всё приложение.
 *
 * Живёт отдельно от KLHttp потому, что зовут её с двух сторон и по-разному.
 * KLTls ведёт рукопожатие сам и получает цепочку готовым списком; системные
 * же пути отдают SecTrustRef. Проверка при этом обязана быть одна: две
 * похожие расходятся молча, и расхождение видно только на устройстве.
 *
 * Хранилище системы остаётся главным: сначала спрашиваем его, и лишь если
 * оно отказало — добавляем свои корни. На новом устройстве отрабатывает
 * первый путь, и поведение приложения ничем не отличается от обычного.
 */

/** Проверяет цепочку, полученную списком SecCertificateRef (лист первым). */
BOOL KLTrustChainIsValid(NSArray *chain, NSString *host);

/** То же для объекта доверия, который приносит система. */
BOOL KLTrustIsValid(SecTrustRef trust, NSString *host);

/** Вшитые корни из Resources/certs как SecCertificateRef. Читаются один раз. */
NSArray *KLBundledAnchors(void);
